#include<iostream>
using namespace std;
 int main(){
   int x=10;
   float y=100.344;
   x=x+1;
   cout<<x<<endl;
   x+=1;
   cout<<x<<endl;
   cout<<x++<<endl;//here value is printed then incresed
   cout<<x--<<endl;
   cout<<++x<<endl;//here value is incresed then printed
   cout<<--x<<endl;
   cout<<x+12<<endl;
   cout<<x+y<<endl;

    return 0;
 
 }